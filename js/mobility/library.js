// Alles zusammen, mit Einordnung
export const EXERCISES = [
  ...BASE_EXERCISES.map((ex) => ({ ...ex, ...(META[ex.id] || {}) })),
  ...EXTRA,
  ...PLAN_EXTRA,
  ...KICK_EXTRA,
  ...LOWER_EXTRA,
];
const BY_ID = new Map(EXERCISES.map((e) => [e.id, e]));
// Stufen in beide Richtungen verknüpfen: up = nächste Stufe, down = leichtere
EXERCISES.forEach((e) => {
  const next = e.up && BY_ID.get(e.up);
  if (next && !next.down) next.down = e.id;
});
export function exercise(id) { return BY_ID.get(id) || null; }

export function exercisesOfRegion(region) {
  return EXERCISES.filter((e) => e.regions.includes(region));
}

// Übungen, die sich gegenseitig ersetzen können (gleiche Hauptregion, gleiche Art)
export function alternativesFor(id, exclude = []) {
  const ex = exercise(id);
  if (!ex) return [];
  const main = ex.regions[0];
  return EXERCISES.filter((e) => e.id !== id && !exclude.includes(e.id) && e.regions[0] === main && e.kind === ex.kind);
}
